// src/api/fantasyApi.ts
import mockDriverFile from '../../mock_predictions.json';
import mockConstructorFile from '../../mock_constructors.json';
import mockStatsFile from '../../mock_stats.json';
import type {
    CardItem,
    Constructor,
    ConstructorPrediction,
    Driver,
    DriverPrediction,
    Race,
    RoundPredictions,
    StatsEntry,
    StatsFile,
    Track,
} from '../types/f1';

const API_BASE = 'http://localhost:8000';
const SEASON = '2026';

type MockFile<T> = Record<string, Record<string, Record<string, T>>>;
const DRIVER_MOCKS = (mockDriverFile as MockFile<DriverPrediction>)[SEASON];
const CONSTRUCTOR_MOCKS = (mockConstructorFile as MockFile<ConstructorPrediction>)[SEASON];
const STATS_MOCK = (mockStatsFile as Record<string, StatsFile>)[SEASON];

// Mock driver keys that differ from the names in the fantasy data
const DRIVER_ALIASES: Record<string, string> = {
    kimi_antonelli: 'andrea_kimi_antonelli',
    alexander_albon: 'alex_albon',
};

// Team ids used by predictionconstmocker.py
const TEAM_IDS: Record<string, string> = {
    'red bull racing': '1',
    mercedes: '2',
    ferrari: '3',
    mclaren: '4',
    'aston martin': '5',
    alpine: '6',
    williams: '7',
    'racing bulls': '8',
    audi: '9',
    'haas f1 team': '10',
    cadillac: '11',
};

const toKey = (name: string) =>
    name
        .toLowerCase()
        .normalize('NFD')
        .replace(/[̀-ͯ]/g, '')
        .replace(/[^a-z]+/g, '_')
        .replace(/^_|_$/g, '');

const driverKey = (name: string) => {
    const key = toKey(name);
    return DRIVER_ALIASES[key] ?? key;
};

export async function fetchDrivers(): Promise<Driver[]> {
    const res = await fetch(`${API_BASE}/drivers/`);
    if (!res.ok) throw new Error('Failed to fetch drivers from the FastAPI server.');
    return res.json();
}

export async function fetchConstructors(): Promise<Constructor[]> {
    const res = await fetch(`${API_BASE}/constructors/`);
    if (!res.ok) throw new Error('Failed to fetch constructors from the FastAPI server.');
    return res.json();
}

// TODO: swap to the backend once the prediction endpoints exist
export async function fetchPredictions(round: string): Promise<RoundPredictions> {
    return {
        drivers: DRIVER_MOCKS[round] ?? {},
        constructors: CONSTRUCTOR_MOCKS[round] ?? {},
    };
}

// TODO: swap to the backend once the stats endpoint exists (generated by statsMocker.py for now)
export async function fetchStats(): Promise<StatsFile> {
    return STATS_MOCK;
}

export function getTrack(round: string): Track {
    return STATS_MOCK.tracks[round];
}

export function getRaces(): Race[] {
    return Object.entries(DRIVER_MOCKS)
        .map(([round, drivers]) => {
            const first = Object.values(drivers)[0];
            return { round, name: first.race_name, date: first.date };
        })
        .sort((a, b) => Number(a.round) - Number(b.round));
}

// Only races that haven't happened yet (falls back to the last race at the end of the season)
export function getUpcomingRaces(today = new Date()): Race[] {
    const races = getRaces();
    const todayStr = today.toISOString().slice(0, 10);
    const upcoming = races.filter((r) => r.date >= todayStr);
    return upcoming.length ? upcoming : races.slice(-1);
}

const statsFields = (s: StatsEntry | undefined, track: Track) =>
    s && {
        ratings: { ...s.ratings, trackFit: s.trackFit[track.type] },
        season: s.season,
        trackAvg: s.trackHistory[track.circuitRef],
    };

export function buildDriverCards(
    drivers: Driver[],
    predictions: RoundPredictions | null,
    stats: StatsFile | null,
    track: Track
): CardItem[] {
    // The backend can list the same driver twice (old and new seat), keep the most owned one
    const byName = new Map<string, Driver>();
    for (const d of drivers) {
        const existing = byName.get(d.name);
        if (!existing || d.ownership > existing.ownership) byName.set(d.name, d);
    }

    return [...byName.values()].map((d) => {
        const pred = predictions?.drivers[driverKey(d.name)];
        const lastName = d.name.split(' ').slice(-1)[0];
        return {
            id: d.id,
            kind: 'driver',
            name: d.name,
            code: d.code || lastName.slice(0, 3).toUpperCase(),
            number: d.number,
            team: d.team,
            price: Number(d.price) || 0,
            ownership: Number(d.ownership) || 0,
            avatarColor: d.avatarColor || '#2dd4bf',
            floor: pred?.fantasy_points.floor_p10 ?? 0,
            expectedPoints: pred?.fantasy_points.expected_p50 ?? 0,
            ceiling: pred?.fantasy_points.ceiling_p90 ?? 0,
            qualiPos: pred?.predictions.qualifying_position,
            racePos: pred?.predictions.race_position,
            dnfChance: pred?.predictions.dnf_probability,
            ...statsFields(stats?.drivers[toKey(d.name)], track),
        };
    });
}

export function buildConstructorCards(
    constructors: Constructor[],
    predictions: RoundPredictions | null,
    stats: StatsFile | null,
    track: Track
): CardItem[] {
    return constructors.map((c) => {
        const pred = predictions?.constructors[TEAM_IDS[c.name.toLowerCase()]];
        const s = stats?.constructors[toKey(c.name)];
        return {
            id: c.id,
            kind: 'constructor',
            name: c.name,
            code: c.code || c.name.slice(0, 3).toUpperCase(),
            team: 'Constructor',
            price: Number(c.price) || 0,
            ownership: Number(c.ownership) || 0,
            avatarColor: c.avatarColor || '#2dd4bf',
            floor: pred?.fantasy_points.floor_p10 ?? 0,
            expectedPoints: pred?.fantasy_points.expected_p50 ?? 0,
            ceiling: pred?.fantasy_points.ceiling_p90 ?? 0,
            dnfChance: s?.season.starts ? Math.round((s.season.dnfs / s.season.starts) * 100) : undefined,
            ...statsFields(s, track),
        };
    });
}
